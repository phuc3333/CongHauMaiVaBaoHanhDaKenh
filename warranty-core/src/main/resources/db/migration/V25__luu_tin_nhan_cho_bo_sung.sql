-- Keep channel messages that cannot yet be linked to a warranty case visible to CSKH.
CREATE TABLE public.tin_nhan_cho_bo_sung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kenh_id BIGINT NOT NULL REFERENCES public.kenh_goc(id),
    ma_tin_goc VARCHAR(255) NOT NULL,
    ma_nguoi_dung_kenh VARCHAR(255) NOT NULL,
    noi_dung TEXT NOT NULL,
    ho_so_id BIGINT REFERENCES public.ho_so(id),
    ly_do VARCHAR(40) NOT NULL,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_BO_SUNG'
        CHECK (trang_thai IN ('CHO_BO_SUNG', 'DA_GAN_HO_SO', 'DA_DONG')),
    nhan_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kenh_id, ma_tin_goc)
);

CREATE INDEX idx_tin_nhan_cho_bo_sung_moi_nhat
    ON public.tin_nhan_cho_bo_sung (trang_thai, nhan_luc DESC);

CREATE OR REPLACE VIEW public.v_tin_nhan_cho_bo_sung AS
SELECT t.id, kg.ma_kenh, t.ma_tin_goc, t.ma_nguoi_dung_kenh,
       t.noi_dung, t.ly_do, t.trang_thai, t.nhan_luc, t.ho_so_id
FROM public.tin_nhan_cho_bo_sung t
JOIN public.kenh_goc kg ON kg.id = t.kenh_id;

ALTER TABLE public.tin_nhan_cho_bo_sung OWNER TO hau_mai_owner;
ALTER VIEW public.v_tin_nhan_cho_bo_sung OWNER TO hau_mai_owner;
REVOKE ALL ON TABLE public.tin_nhan_cho_bo_sung FROM PUBLIC;
REVOKE ALL ON TABLE public.v_tin_nhan_cho_bo_sung FROM PUBLIC;
GRANT SELECT ON TABLE public.v_tin_nhan_cho_bo_sung TO hau_mai_app;

CREATE OR REPLACE PROCEDURE public.sp_luu_tin_cho_bo_sung(
    IN p_ma_kenh VARCHAR(30),
    IN p_ma_tin_goc VARCHAR(255),
    IN p_ma_nguoi_dung_kenh VARCHAR(255),
    IN p_noi_dung TEXT,
    IN p_ly_do VARCHAR(40),
    IN p_nhan_luc TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_kenh_id BIGINT;
BEGIN
    SELECT id INTO v_kenh_id
    FROM public.kenh_goc
    WHERE ma_kenh = UPPER(BTRIM(p_ma_kenh)) AND dang_bat = TRUE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Kênh % chưa được cấu hình hoặc đang tắt', p_ma_kenh;
    END IF;
    IF NULLIF(BTRIM(p_ma_tin_goc), '') IS NULL
       OR NULLIF(BTRIM(p_ma_nguoi_dung_kenh), '') IS NULL
       OR NULLIF(BTRIM(p_noi_dung), '') IS NULL THEN
        RAISE EXCEPTION 'Thiếu mã tin, mã người gửi hoặc nội dung';
    END IF;

    INSERT INTO public.tin_nhan_cho_bo_sung (
        kenh_id, ma_tin_goc, ma_nguoi_dung_kenh, noi_dung, ly_do, nhan_luc
    ) VALUES (
        v_kenh_id, BTRIM(p_ma_tin_goc), BTRIM(p_ma_nguoi_dung_kenh),
        BTRIM(p_noi_dung), COALESCE(NULLIF(BTRIM(p_ly_do), ''), 'CAN_FORM'),
        COALESCE(p_nhan_luc, now())
    ) ON CONFLICT (kenh_id, ma_tin_goc) DO NOTHING;
END;
$$;

ALTER PROCEDURE public.sp_luu_tin_cho_bo_sung(VARCHAR, VARCHAR, VARCHAR, TEXT, VARCHAR, TIMESTAMPTZ)
    OWNER TO hau_mai_owner;
REVOKE EXECUTE ON PROCEDURE public.sp_luu_tin_cho_bo_sung(VARCHAR, VARCHAR, VARCHAR, TEXT, VARCHAR, TIMESTAMPTZ)
    FROM PUBLIC;
GRANT EXECUTE ON PROCEDURE public.sp_luu_tin_cho_bo_sung(VARCHAR, VARCHAR, VARCHAR, TEXT, VARCHAR, TIMESTAMPTZ)
    TO hau_mai_app;

CREATE OR REPLACE PROCEDURE public.sp_gan_tin_cho_bo_sung_vao_ho_so(
    IN p_ma_kenh VARCHAR(30),
    IN p_ma_nguoi_dung_kenh VARCHAR(255),
    IN p_ho_so_id BIGINT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_kenh_id BIGINT;
BEGIN
    SELECT kg.id INTO v_kenh_id
    FROM public.kenh_goc kg
    JOIN public.dinh_danh_kenh dk ON dk.kenh_id = kg.id
    JOIN public.ho_so hs ON hs.khach_hang_id = dk.khach_hang_id AND hs.kenh_goc_id = kg.id
    WHERE kg.ma_kenh = UPPER(BTRIM(p_ma_kenh))
      AND dk.ma_nguoi_dung_kenh = p_ma_nguoi_dung_kenh
      AND hs.id = p_ho_so_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    INSERT INTO public.tin_nhan (
        ho_so_id, kenh_id, ma_tin_goc, huong_tin, noi_dung,
        nhan_vien_id, trang_thai_gui, tao_luc
    )
    SELECT p_ho_so_id, t.kenh_id, t.ma_tin_goc, 'DEN', t.noi_dung,
           NULL, 'KHONG_AP_DUNG', t.nhan_luc
    FROM public.tin_nhan_cho_bo_sung t
    WHERE t.kenh_id = v_kenh_id
      AND t.ma_nguoi_dung_kenh = p_ma_nguoi_dung_kenh
      AND t.trang_thai = 'CHO_BO_SUNG'
    ON CONFLICT (kenh_id, ma_tin_goc) WHERE ma_tin_goc IS NOT NULL DO NOTHING;

    UPDATE public.tin_nhan_cho_bo_sung
    SET trang_thai = 'DA_GAN_HO_SO', ho_so_id = p_ho_so_id
    WHERE kenh_id = v_kenh_id
      AND ma_nguoi_dung_kenh = p_ma_nguoi_dung_kenh
      AND trang_thai = 'CHO_BO_SUNG';
END;
$$;

ALTER PROCEDURE public.sp_gan_tin_cho_bo_sung_vao_ho_so(VARCHAR, VARCHAR, BIGINT)
    OWNER TO hau_mai_owner;
REVOKE EXECUTE ON PROCEDURE public.sp_gan_tin_cho_bo_sung_vao_ho_so(VARCHAR, VARCHAR, BIGINT)
    FROM PUBLIC;
GRANT EXECUTE ON PROCEDURE public.sp_gan_tin_cho_bo_sung_vao_ho_so(VARCHAR, VARCHAR, BIGINT)
    TO hau_mai_app;
