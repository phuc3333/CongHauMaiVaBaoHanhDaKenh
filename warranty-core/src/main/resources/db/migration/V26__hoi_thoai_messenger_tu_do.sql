INSERT INTO public.cuoc_tro_chuyen (kenh_id, ma_nguoi_dung_kenh, ho_so_id, cap_nhat_luc)
SELECT DISTINCT ON (t.kenh_id, t.ma_nguoi_dung_kenh)
       t.kenh_id, t.ma_nguoi_dung_kenh, t.ho_so_id, t.nhan_luc
FROM public.tin_nhan_cho_bo_sung t
ORDER BY t.kenh_id, t.ma_nguoi_dung_kenh, t.nhan_luc DESC
ON CONFLICT (kenh_id, ma_nguoi_dung_kenh) DO NOTHING;

INSERT INTO public.tin_nhan_cuoc_tro_chuyen (
    cuoc_tro_chuyen_id, ho_so_id, ma_tin_goc, huong_tin, noi_dung, tao_luc
)
SELECT c.id, p.ho_so_id, p.ma_tin_goc, 'DEN', p.noi_dung, p.nhan_luc
FROM public.tin_nhan_cho_bo_sung p
JOIN public.cuoc_tro_chuyen c
  ON c.kenh_id = p.kenh_id AND c.ma_nguoi_dung_kenh = p.ma_nguoi_dung_kenh
ON CONFLICT DO NOTHING;

-- Preserve existing Messenger customers and case history when upgrading.
INSERT INTO public.cuoc_tro_chuyen (kenh_id, ma_nguoi_dung_kenh, khach_hang_id, ho_so_id)
SELECT DISTINCT ON (dk.kenh_id, dk.ma_nguoi_dung_kenh)
       dk.kenh_id, dk.ma_nguoi_dung_kenh, dk.khach_hang_id, hs.id
FROM public.dinh_danh_kenh dk
JOIN public.kenh_goc kg ON kg.id=dk.kenh_id AND kg.ma_kenh='FACEBOOK'
LEFT JOIN public.ho_so hs ON hs.khach_hang_id=dk.khach_hang_id AND hs.kenh_goc_id=dk.kenh_id
ORDER BY dk.kenh_id, dk.ma_nguoi_dung_kenh, hs.ngay_tiep_nhan DESC NULLS LAST
ON CONFLICT (kenh_id, ma_nguoi_dung_kenh) DO UPDATE SET
    khach_hang_id=EXCLUDED.khach_hang_id,
    ho_so_id=COALESCE(EXCLUDED.ho_so_id, public.cuoc_tro_chuyen.ho_so_id);

INSERT INTO public.tin_nhan_cuoc_tro_chuyen (
    cuoc_tro_chuyen_id, ho_so_id, ma_tin_goc, huong_tin, noi_dung,
    trang_thai_gui, nhan_vien_id, tao_luc, gui_luc
)
SELECT c.id, tn.ho_so_id, tn.ma_tin_goc, tn.huong_tin, tn.noi_dung,
       tn.trang_thai_gui, tn.nhan_vien_id, tn.tao_luc, tn.gui_luc
FROM public.tin_nhan tn
JOIN public.ho_so hs ON hs.id=tn.ho_so_id
JOIN public.kenh_goc kg ON kg.id=tn.kenh_id AND kg.ma_kenh='FACEBOOK'
JOIN public.dinh_danh_kenh dk ON dk.kenh_id=kg.id AND dk.khach_hang_id=hs.khach_hang_id
JOIN public.cuoc_tro_chuyen c ON c.kenh_id=kg.id AND c.ma_nguoi_dung_kenh=dk.ma_nguoi_dung_kenh
ON CONFLICT (cuoc_tro_chuyen_id, ma_tin_goc) WHERE ma_tin_goc IS NOT NULL DO NOTHING;

CREATE OR REPLACE VIEW public.v_cuoc_tro_chuyen AS
SELECT c.id, kg.ma_kenh, c.ma_nguoi_dung_kenh, c.khach_hang_id, c.ho_so_id,
       c.cap_nhat_luc,
       (SELECT m.noi_dung FROM public.tin_nhan_cuoc_tro_chuyen m
        WHERE m.cuoc_tro_chuyen_id = c.id ORDER BY m.tao_luc DESC, m.id DESC LIMIT 1) AS tin_moi_nhat
FROM public.cuoc_tro_chuyen c
JOIN public.kenh_goc kg ON kg.id = c.kenh_id;

CREATE OR REPLACE VIEW public.v_tin_nhan_cuoc_tro_chuyen AS
SELECT m.id, m.cuoc_tro_chuyen_id, m.ho_so_id, m.ma_tin_goc,
       m.huong_tin, m.noi_dung, m.trang_thai_gui, m.tao_luc, m.gui_luc
FROM public.tin_nhan_cuoc_tro_chuyen m;

