    OWNER TO hau_mai_owner;
REVOKE EXECUTE ON PROCEDURE public.sp_cap_nhat_gui_cuoc_tro_chuyen(BIGINT, VARCHAR, VARCHAR, TIMESTAMPTZ) FROM PUBLIC;
