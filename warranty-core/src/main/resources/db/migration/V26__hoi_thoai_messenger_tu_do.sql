CREATE OR REPLACE PROCEDURE public.sp_gan_cuoc_tro_chuyen_vao_ho_so(
    IN p_ma_kenh VARCHAR(30), IN p_ma_nguoi_dung VARCHAR(255), IN p_ho_so_id BIGINT
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_kenh_id BIGINT; v_khach_hang_id BIGINT;
BEGIN
    SELECT hs.kenh_goc_id, hs.khach_hang_id INTO v_kenh_id, v_khach_hang_id
    FROM public.ho_so hs JOIN public.kenh_goc kg ON kg.id=hs.kenh_goc_id
    JOIN public.dinh_danh_kenh dk ON dk.kenh_id=kg.id AND dk.khach_hang_id=hs.khach_hang_id
    WHERE hs.id=p_ho_so_id AND kg.ma_kenh=UPPER(BTRIM(p_ma_kenh))
      AND dk.ma_nguoi_dung_kenh=p_ma_nguoi_dung;
    IF NOT FOUND THEN RETURN; END IF;
    INSERT INTO public.cuoc_tro_chuyen(kenh_id, ma_nguoi_dung_kenh, khach_hang_id, ho_so_id)
    VALUES (v_kenh_id, p_ma_nguoi_dung, v_khach_hang_id, p_ho_so_id)
    ON CONFLICT(kenh_id, ma_nguoi_dung_kenh) DO UPDATE SET
        khach_hang_id=EXCLUDED.khach_hang_id, ho_so_id=EXCLUDED.ho_so_id, cap_nhat_luc=now();
    UPDATE public.tin_nhan_cuoc_tro_chuyen m SET ho_so_id=p_ho_so_id
    FROM public.cuoc_tro_chuyen c
    WHERE c.id=m.cuoc_tro_chuyen_id AND c.kenh_id=v_kenh_id
      AND c.ma_nguoi_dung_kenh=p_ma_nguoi_dung;
END; $$;
ALTER PROCEDURE public.sp_gan_cuoc_tro_chuyen_vao_ho_so(VARCHAR, VARCHAR, BIGINT) OWNER TO hau_mai_owner;
REVOKE EXECUTE ON PROCEDURE public.sp_gan_cuoc_tro_chuyen_vao_ho_so(VARCHAR, VARCHAR, BIGINT) FROM PUBLIC;
GRANT EXECUTE ON PROCEDURE public.sp_gan_cuoc_tro_chuyen_vao_ho_so(VARCHAR, VARCHAR, BIGINT) TO hau_mai_app;
