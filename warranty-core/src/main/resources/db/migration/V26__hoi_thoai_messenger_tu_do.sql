CREATE OR REPLACE PROCEDURE public.sp_tao_phan_hoi_cuoc_tro_chuyen(
    IN p_cuoc_tro_chuyen_id BIGINT, IN p_nhan_vien_id BIGINT, IN p_noi_dung TEXT,
    IN p_now TIMESTAMPTZ, OUT p_tin_nhan_id BIGINT, OUT p_ma_kenh VARCHAR, OUT p_recipient VARCHAR
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_kenh_id BIGINT;
BEGIN
    IF NULLIF(BTRIM(p_noi_dung), '') IS NULL OR LENGTH(p_noi_dung) > 2000 THEN
        RAISE EXCEPTION 'Nội dung phải từ 1 đến 2000 ký tự';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.nhan_vien nv JOIN public.tai_khoan tk ON tk.id=nv.tai_khoan_id
        WHERE nv.id=p_nhan_vien_id AND tk.vai_tro='CSKH' AND tk.dang_hoat_dong) THEN
        RAISE EXCEPTION 'Nhân viên CSKH không hoạt động';
    END IF;
    SELECT c.kenh_id, kg.ma_kenh, c.ma_nguoi_dung_kenh
    INTO v_kenh_id, p_ma_kenh, p_recipient
    FROM public.cuoc_tro_chuyen c JOIN public.kenh_goc kg ON kg.id=c.kenh_id
    WHERE c.id=p_cuoc_tro_chuyen_id AND kg.ma_kenh='FACEBOOK';
    IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy cuộc trò chuyện'; END IF;
    INSERT INTO public.tin_nhan_cuoc_tro_chuyen(
        cuoc_tro_chuyen_id, ho_so_id, huong_tin, noi_dung, trang_thai_gui,
        nhan_vien_id, tao_luc
    ) VALUES (p_cuoc_tro_chuyen_id, NULL, 'DI', BTRIM(p_noi_dung), 'CHO_GUI',
        p_nhan_vien_id, COALESCE(p_now, now())) RETURNING id INTO p_tin_nhan_id;
    UPDATE public.cuoc_tro_chuyen SET cap_nhat_luc=COALESCE(p_now, now())
    WHERE id=p_cuoc_tro_chuyen_id;
END; $$;
ALTER PROCEDURE public.sp_tao_phan_hoi_cuoc_tro_chuyen(BIGINT, BIGINT, TEXT, TIMESTAMPTZ)
    OWNER TO hau_mai_owner;
REVOKE EXECUTE ON PROCEDURE public.sp_tao_phan_hoi_cuoc_tro_chuyen(BIGINT, BIGINT, TEXT, TIMESTAMPTZ) FROM PUBLIC;
GRANT EXECUTE ON PROCEDURE public.sp_tao_phan_hoi_cuoc_tro_chuyen(BIGINT, BIGINT, TEXT, TIMESTAMPTZ) TO hau_mai_app;

CREATE OR REPLACE PROCEDURE public.sp_cap_nhat_gui_cuoc_tro_chuyen(
    IN p_tin_nhan_id BIGINT, IN p_trang_thai VARCHAR(20), IN p_ma_tin_goc VARCHAR(255), IN p_now TIMESTAMPTZ
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    IF p_trang_thai NOT IN ('DA_GUI', 'THAT_BAI') THEN RAISE EXCEPTION 'Trạng thái gửi không hợp lệ'; END IF;
    UPDATE public.tin_nhan_cuoc_tro_chuyen SET trang_thai_gui=p_trang_thai,
        ma_tin_goc=COALESCE(NULLIF(BTRIM(p_ma_tin_goc), ''), ma_tin_goc),
        gui_luc=CASE WHEN p_trang_thai='DA_GUI' THEN COALESCE(p_now, now()) ELSE gui_luc END
    WHERE id=p_tin_nhan_id AND huong_tin='DI';
    IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy tin nhắn chờ gửi'; END IF;
END; $$;
