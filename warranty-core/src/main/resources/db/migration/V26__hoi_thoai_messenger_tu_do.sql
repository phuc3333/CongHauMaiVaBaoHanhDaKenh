-- Conversations exist independently of warranty cases. A conversation can be linked later.
CREATE TABLE public.cuoc_tro_chuyen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kenh_id BIGINT NOT NULL REFERENCES public.kenh_goc(id),
    ma_nguoi_dung_kenh VARCHAR(255) NOT NULL,
    khach_hang_id BIGINT REFERENCES public.khach_hang(id),
    ho_so_id BIGINT REFERENCES public.ho_so(id),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    cap_nhat_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kenh_id, ma_nguoi_dung_kenh)
);

CREATE TABLE public.tin_nhan_cuoc_tro_chuyen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuoc_tro_chuyen_id BIGINT NOT NULL REFERENCES public.cuoc_tro_chuyen(id),
    ho_so_id BIGINT REFERENCES public.ho_so(id),
    ma_tin_goc VARCHAR(255),
    huong_tin VARCHAR(10) NOT NULL CHECK (huong_tin IN ('DEN', 'DI')),
    noi_dung TEXT NOT NULL,
    trang_thai_gui VARCHAR(20) NOT NULL DEFAULT 'KHONG_AP_DUNG'
        CHECK (trang_thai_gui IN ('KHONG_AP_DUNG', 'CHO_GUI', 'DA_GUI', 'THAT_BAI')),
    nhan_vien_id BIGINT REFERENCES public.nhan_vien(id),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    gui_luc TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_tin_nhan_cuoc_tro_chuyen_external
    ON public.tin_nhan_cuoc_tro_chuyen(cuoc_tro_chuyen_id, ma_tin_goc)
    WHERE ma_tin_goc IS NOT NULL;
CREATE INDEX idx_tin_nhan_cuoc_tro_chuyen_time
    ON public.tin_nhan_cuoc_tro_chuyen(cuoc_tro_chuyen_id, tao_luc);

