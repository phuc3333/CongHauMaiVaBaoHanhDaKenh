CREATE TABLE tai_khoan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_dang_nhap VARCHAR(100) NOT NULL UNIQUE,
    mat_khau_bam VARCHAR(255) NOT NULL,
    vai_tro VARCHAR(30) NOT NULL CHECK (vai_tro IN ('CSKH', 'DIEU_PHOI_VIEN', 'KY_THUAT_VIEN')),
    dang_hoat_dong BOOLEAN NOT NULL DEFAULT TRUE,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE nhan_vien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tai_khoan_id BIGINT NOT NULL UNIQUE REFERENCES tai_khoan(id),
    ho_ten VARCHAR(200) NOT NULL,
    so_dien_thoai VARCHAR(30),
    email VARCHAR(255)
);

CREATE TABLE khach_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_ten VARCHAR(200),
    so_dien_thoai VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(255),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE kenh_goc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_kenh VARCHAR(30) NOT NULL UNIQUE CHECK (ma_kenh IN ('WEBSITE', 'EMAIL', 'FACEBOOK', 'ZALO')),
    ten_hien_thi VARCHAR(100) NOT NULL,
    dang_bat BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dinh_danh_kenh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    khach_hang_id BIGINT NOT NULL REFERENCES khach_hang(id),
    kenh_id BIGINT NOT NULL REFERENCES kenh_goc(id),
    ma_nguoi_dung_kenh VARCHAR(255) NOT NULL,
    ten_hien_thi VARCHAR(200),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kenh_id, ma_nguoi_dung_kenh)
);

CREATE TABLE san_pham (
    serial VARCHAR(100) PRIMARY KEY,
    ten_san_pham VARCHAR(200) NOT NULL,
    ngay_mua DATE,
    thoi_han_bao_hanh_thang INTEGER CHECK (thoi_han_bao_hanh_thang IS NULL OR thoi_han_bao_hanh_thang >= 0),
    ngay_het_han_bao_hanh DATE
);

CREATE TABLE ho_so (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_ho_so VARCHAR(30) NOT NULL UNIQUE,
    khach_hang_id BIGINT NOT NULL REFERENCES khach_hang(id),
    serial VARCHAR(100) REFERENCES san_pham(serial),
    kenh_goc_id BIGINT NOT NULL REFERENCES kenh_goc(id),
    mo_ta_loi TEXT NOT NULL,
    ngay_tiep_nhan TIMESTAMPTZ NOT NULL DEFAULT now(),
    trang_thai VARCHAR(40) NOT NULL CHECK (trang_thai IN (
        'MOI', 'DANG_XAC_MINH', 'CHO_KHACH_BO_SUNG', 'CHO_PHAN_CONG',
        'DANG_SUA_CHUA', 'DA_SUA_XONG', 'TU_CHOI', 'DA_DONG', 'CHO_CSKH_XU_LY'
    )),
    ket_qua_xac_minh TEXT,
    ly_do_tu_choi TEXT,
    ket_luan_xu_ly TEXT,
    bat_dau_cho_khach_luc TIMESTAMPTZ,
    ngay_dong TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (trang_thai = 'CHO_KHACH_BO_SUNG' AND bat_dau_cho_khach_luc IS NOT NULL)
        OR (trang_thai <> 'CHO_KHACH_BO_SUNG')
    )
);

CREATE INDEX idx_ho_so_khach_kenh_trang_thai
    ON ho_so(khach_hang_id, kenh_goc_id, trang_thai, ngay_tiep_nhan DESC);

CREATE TABLE lich_su_xu_ly (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_so_id BIGINT NOT NULL REFERENCES ho_so(id),
    trang_thai_tu VARCHAR(40),
    trang_thai_sang VARCHAR(40) NOT NULL,
    loai_tac_nhan VARCHAR(20) NOT NULL CHECK (loai_tac_nhan IN ('NHAN_VIEN', 'KHACH_HANG', 'HE_THONG')),
    nhan_vien_id BIGINT REFERENCES nhan_vien(id),
    ghi_chu TEXT,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tin_nhan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_so_id BIGINT NOT NULL REFERENCES ho_so(id),
    kenh_id BIGINT NOT NULL REFERENCES kenh_goc(id),
    ma_tin_goc VARCHAR(255),
    huong_tin VARCHAR(10) NOT NULL CHECK (huong_tin IN ('DEN', 'DI')),
    noi_dung TEXT NOT NULL,
    nhan_vien_id BIGINT REFERENCES nhan_vien(id),
    trang_thai_gui VARCHAR(20) NOT NULL DEFAULT 'KHONG_AP_DUNG'
        CHECK (trang_thai_gui IN ('KHONG_AP_DUNG', 'CHO_GUI', 'DA_GUI', 'THAT_BAI')),
    gui_luc TIMESTAMPTZ,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_tin_nhan_kenh_ma_goc
    ON tin_nhan(kenh_id, ma_tin_goc)
    WHERE ma_tin_goc IS NOT NULL;

CREATE INDEX idx_tin_nhan_ho_so_thoi_gian ON tin_nhan(ho_so_id, tao_luc);

CREATE TABLE phan_cong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_so_id BIGINT NOT NULL REFERENCES ho_so(id),
    ky_thuat_vien_id BIGINT NOT NULL REFERENCES nhan_vien(id),
    dieu_phoi_vien_id BIGINT NOT NULL REFERENCES nhan_vien(id),
    ngay_phan_cong TIMESTAMPTZ NOT NULL DEFAULT now(),
    ngay_ket_thuc TIMESTAMPTZ,
    ly_do_thay_doi TEXT,
    dang_hieu_luc BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uq_phan_cong_dang_hieu_luc_ho_so
    ON phan_cong(ho_so_id)
    WHERE dang_hieu_luc = TRUE;

CREATE INDEX idx_phan_cong_ky_thuat_vien_hieu_luc
    ON phan_cong(ky_thuat_vien_id, dang_hieu_luc);

CREATE TABLE tien_do_sua_chua (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phan_cong_id BIGINT NOT NULL REFERENCES phan_cong(id),
    trang_thai VARCHAR(30) NOT NULL CHECK (trang_thai IN (
        'DA_NHAN_THIET_BI', 'DANG_KIEM_TRA', 'DANG_SUA_CHUA',
        'CHO_LINH_KIEN', 'DANG_KIEM_TRA_LAI', 'DA_SUA_XONG', 'KHONG_THE_SUA'
    )),
    ghi_chu TEXT,
    de_xuat_linh_kien TEXT,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tep_dinh_kem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tin_nhan_id BIGINT REFERENCES tin_nhan(id),
    tien_do_id BIGINT REFERENCES tien_do_sua_chua(id),
    ten_tep VARCHAR(255) NOT NULL,
    duong_dan_luu TEXT NOT NULL,
    loai_mime VARCHAR(150),
    kich_thuoc_bytes BIGINT CHECK (kich_thuoc_bytes IS NULL OR kich_thuoc_bytes >= 0),
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (tin_nhan_id IS NOT NULL AND tien_do_id IS NULL)
        OR (tin_nhan_id IS NULL AND tien_do_id IS NOT NULL)
    )
);

CREATE TABLE sla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_so_id BIGINT NOT NULL REFERENCES ho_so(id),
    loai_sla VARCHAR(20) NOT NULL CHECK (loai_sla IN ('TIEP_NHAN', 'XU_LY')),
    thoi_han_phut INTEGER NOT NULL CHECK (thoi_han_phut > 0),
    thoi_diem_bat_dau TIMESTAMPTZ NOT NULL DEFAULT now(),
    thoi_diem_ket_thuc TIMESTAMPTZ,
    thoi_gian_tam_dung_phut BIGINT NOT NULL DEFAULT 0 CHECK (thoi_gian_tam_dung_phut >= 0),
    thoi_diem_tam_dung TIMESTAMPTZ,
    trang_thai VARCHAR(20) NOT NULL CHECK (trang_thai IN (
        'DANG_DEM', 'TAM_DUNG', 'DA_QUA_HAN', 'DAT_SLA', 'KHONG_DAT_SLA'
    )),
    UNIQUE (ho_so_id, loai_sla)
);

CREATE TABLE vi_pham_sla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sla_id BIGINT NOT NULL UNIQUE REFERENCES sla(id),
    thoi_diem_phat_hien TIMESTAMPTZ NOT NULL DEFAULT now(),
    muc_do VARCHAR(30) NOT NULL,
    noi_dung TEXT,
    da_xu_ly BOOLEAN NOT NULL DEFAULT FALSE,
    nhan_vien_xu_ly_id BIGINT REFERENCES nhan_vien(id)
);

CREATE TABLE thong_bao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_so_id BIGINT REFERENCES ho_so(id),
    nhan_vien_nhan_id BIGINT NOT NULL REFERENCES nhan_vien(id),
    khoa_chong_trung VARCHAR(255) NOT NULL UNIQUE,
    tieu_de VARCHAR(255) NOT NULL,
    noi_dung TEXT NOT NULL,
    loai_thong_bao VARCHAR(40) NOT NULL,
    da_doc BOOLEAN NOT NULL DEFAULT FALSE,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cau_hinh (
    ma_cau_hinh VARCHAR(100) PRIMARY KEY,
    gia_tri VARCHAR(500) NOT NULL,
    mo_ta TEXT,
    cap_nhat_luc TIMESTAMPTZ NOT NULL DEFAULT now()
);